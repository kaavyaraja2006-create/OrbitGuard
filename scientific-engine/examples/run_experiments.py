"""Run the research experiments E1-E8 and write machine-readable results.

    python examples/run_experiments.py                 # all, 5 seeds, fast profile
    python examples/run_experiments.py E3 E6 --seeds 10 --profile full

Writes research/experiments/results/<E>.json and <E>.csv plus a summary.md of
whatever the runs produced. Nothing is edited by hand.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from orbitguard_engine.experiments import EXPERIMENTS, run_experiment, to_csv  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "research" / "experiments" / "results"


def fmt(v, k):
    if v is None:
        return "—"
    if k in ("success", "p_violation_independent", "selected_rate"):
        return f"{v * 100:.0f}%" if k != "p_violation_independent" else f"{v * 100:.1f}%"
    if k == "dv_ms":
        return f"{v * 1000:.1f}"
    if k == "raan_rate_change_deg_day":
        return f"{v:.1e}"
    return f"{v:.2f}" if abs(v) < 100 else f"{v:.0f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("names", nargs="*", default=list(EXPERIMENTS))
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--profile", default="fast", choices=["fast", "full"])
    ap.add_argument("--summary-only", action="store_true", help="rebuild summary.md from the JSON files already in results/")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    md = ["# ORBITGUARD research experiments: results", "",
          "SYNTHETIC scenarios, ASSUMED uncertainties. "
          "Generated by `scientific-engine/examples/run_experiments.py`; every number below is copied from the JSON next to this file.", ""]
    cols = ["success", "dv_ms", "p_violation_independent", "violations_after", "new_violations", "min_sep_m", "runtime_s", "raan_rate_change_deg_day"]
    heads = ["success", "Δv mm/s", "indep. P(viol.)", "unsafe after", "new unsafe", "worst miss m", "runtime s", "Δ nodal rate °/d"]
    for name in a.names:
        t0 = time.time()
        if a.summary_only:
            if not (OUT / f"{name}.json").exists():
                continue
            res = json.loads((OUT / f"{name}.json").read_text())
        else:
            print(f"== {name}: {EXPERIMENTS[name][0]}", flush=True)
            res = run_experiment(name, seeds=a.seeds, profile=a.profile, progress=lambda f, m: print(f"   {f:5.1%} {m}", flush=True))
            (OUT / f"{name}.json").write_text(json.dumps(res, indent=1, default=float))
            (OUT / f"{name}.csv").write_text(to_csv(res))
        md += [f"## {name}: {res['title']}", "", f"*{res['question']}*", "",
               "| group | method | n | " + " | ".join(heads) + " |", "|" + "---|" * (3 + len(heads))]
        for s in res["summary"]:
            md.append(f"| {s['group']} | {s['method']} | {s['n']} | " + " | ".join(
                fmt(s.get(f"{c}_mean"), c) + (f" ± {fmt(s.get(f'{c}_std'), c)}" if c in ("dv_ms", "min_sep_m") and s['n'] > 1 else "") for c in cols) + " |")
        if res.get("detail"):
            md += ["", "Selected maneuver (seed 0), with independent validation:", ""] + [f"- {x}" for x in res["detail"].get("explanation") or []]
        md += ["", f"Runtime {res['runtime_s']:.0f} s, {res['seeds']} seeds, profile {res['profile']}. Versions: `{json.dumps(res['versions'])}`.", ""]
        (OUT / "summary.md").write_text("\n".join(md))
    print("written to", OUT)


if __name__ == "__main__":
    main()
